// Existing approved interior photograph only. Keep the original CDN fallback.
import sharp from 'sharp';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const crop = JSON.parse(await readFile('apps/website/src/lib/sceneCrops.json', 'utf8')).cabin;
const output = 'apps/website/src/lib/assets/optimized/cabin/';
const audit = 'artifacts/image-crops/';
await mkdir(output, { recursive: true });
await mkdir(audit, { recursive: true });
const url = (width, quality = 80) => `https://images.unsplash.com/photo-1652453822981-653a9a522a5b?auto=format&fit=crop&w=${width}&q=${quality}`;
let master;
try { master = await readFile('artifacts/vehicle-photo-compression/service.master'); }
catch {
  const response = await fetch(url(2560, 95), { headers: { Accept: 'image/jpeg' } });
  if (!response.ok) throw Error('Approved interior photograph unavailable');
  master = Buffer.from(await response.arrayBuffer());
}
const native = await sharp(master).metadata();
if (native.width !== crop.sourceWidth || native.height !== crop.sourceHeight)
  throw Error('Source dimensions changed; the framing crop must be reviewed again');
const rows = [];
for (const width of [320, 480, 640, 960, 1280, 1600, 1920]) {
  for (const format of ['webp', 'avif']) {
    const before = await fetch(url(width), { headers: { Accept: `image/${format}` } });
    if (!before.ok) throw Error('Current comparison unavailable');
    const original = Buffer.from(await before.arrayBuffer());
    await writeFile(`${audit}cabin-before-${width}.${format}`, original);
    const base = sharp(master).extract({ left: crop.left, top: crop.top, width: crop.width, height: crop.height }).resize({ width, withoutEnlargement: true });
    const buffer = await (format === 'avif'
      ? base.avif({ quality: 70, effort: 5, chromaSubsampling: '4:4:4' })
      : base.webp({ quality: 90, effort: 6, smartSubsample: true })).toBuffer();
    const file = `interior-crop-${width}.${format}`;
    const applied = buffer.length < original.length;
    await writeFile(`${audit}cabin-candidate-${width}.${format}`, buffer);
    if (applied) await writeFile(output + file, buffer);
    rows.push({ width, format, file, before: original.length, after: buffer.length, applied, src: url(width) });
  }
  console.log(JSON.stringify(rows.slice(-2)));
}
let module = '// Generated by scripts/optimize-cabin-images.mjs.\n';
rows.forEach((row, index) => { if (row.applied) module += `import image${index} from './assets/optimized/cabin/${row.file}?url&no-inline';\n`; });
module += 'export const cabinImages = {\n';
for (const format of ['webp', 'avif']) {
  const set = rows.flatMap((row, index) => row.format === format
    ? [row.applied ? '${image' + index + '} ' + row.width + 'w' : row.src + ' ' + row.width + 'w'] : []);
  module += `  ${format}: \`${set.join(', ')}\`,\n`;
}
module += '} as const;\n';
await writeFile('apps/website/src/lib/cabinImages.ts', module);
await writeFile(audit + 'cabin-measurements.json', JSON.stringify(rows, null, 2));
