// Remove only the horizontal margins outside the validated mobile hero frame.
// Keep the approved portrait source, pixel density, quality and desktop assets unchanged.
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
const input = 'apps/website/src/lib/assets/images/hero-directions/forest-ribbon-portrait-1920.webp';
const dir = 'apps/website/src/lib/assets/optimized/home-v5-mobile';
await mkdir(dir, { recursive: true });
const originalWidths = [640, 1080, 1280, 1440, 1472, 1600, 1664, 1728, 1792, 1920];
let source = '// Generated by scripts/optimize-mobile-hero.mjs. Same portrait density and quality.\n';
const groups = [];
for (const cropWidth of [1200, 1440]) {
  const variants = [];
  for (const originalWidth of originalWidths) {
    const width = originalWidth * cropWidth / 1920;
    const base = sharp(input).extract({ left: (1920 - cropWidth) / 2, top: 0, width: cropWidth, height: 2560 }).resize({ width, withoutEnlargement: true });
    for (const format of ['avif', 'webp']) {
      const bytes = await (format === 'avif'
        ? base.clone().avif({ quality: 55, effort: 5, chromaSubsampling: '4:2:0' })
        : base.clone().webp({ quality: 88, effort: 6, smartSubsample: true })).toBuffer();
      const file = `forest-mobile-${cropWidth}-${width}.${format}`, name = `image${groups.length}_${variants.length}`;
      await writeFile(`${dir}/${file}`, bytes);
      source += `import ${name} from './assets/optimized/home-v5-mobile/${file}?url&no-inline';\n`;
      variants.push({ format, width, name, bytes: bytes.length });
    }
  }
  groups.push({ cropWidth, variants });
  console.log(JSON.stringify({ cropWidth, variants }));
}
source += 'export const mobileHeroImages = {\n';
for (const { cropWidth, variants } of groups) {
  source += `  ${cropWidth}: {\n`;
  for (const format of ['avif', 'webp']) source += `    ${format}: \`${variants.filter(v => v.format === format).map(v => '${' + v.name + '} ' + v.width + 'w').join(', ')}\`,\n`;
  source += '  },\n';
}
source += '} as const;\n';
await writeFile('apps/website/src/lib/mobileHeroImages.ts', source);
