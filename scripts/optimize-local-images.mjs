// Deterministic derivatives only. Original artwork and photographs are never overwritten.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const sharp = createRequire(new URL('../backend/package.json', import.meta.url))('sharp');
const website = 'apps/website/src/lib/assets/optimized';
const crm = 'apps/crm/src/lib/assets/optimized';
const records = [];
const save = (file, data) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, data); };
async function derivative(source, output, width, format, options) {
  const input = fs.readFileSync(source);
  const reference = await sharp(input).resize({ width, withoutEnlargement: true, kernel: 'lanczos3' }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const bytes = await sharp(input).resize({ width, withoutEnlargement: true, kernel: 'lanczos3' })[format](options).toBuffer();
  save(output, bytes);
  const decoded = await sharp(bytes).ensureAlpha().raw().toBuffer();
  let error = 0, alphaError = 0, samples = 0;
  for (let i = 0; i < decoded.length; i += 4) {
    alphaError += Math.abs(decoded[i + 3] - reference.data[i + 3]);
    const alpha = reference.data[i + 3] / 255;
    for (let c = 0; c < 3; c++) { error += Math.abs(decoded[i + c] - reference.data[i + c]) * alpha; samples += alpha; }
  }
  const metadata = await sharp(bytes).metadata();
  records.push({ source, output, originalBytes: input.length, bytes: bytes.length, width: metadata.width, height: metadata.height, alpha: metadata.hasAlpha, format, options, visibleMeanError: +(error / Math.max(1, samples)).toFixed(3), alphaMeanError: +(alphaError / (decoded.length / 4)).toFixed(3) });
  return output;
}
const widthSet = [180, 240, 360, 720, 1200, 1881];
for (const [tone, file] of [['light', 'logo-transparent.png'], ['dark', 'logo-transparent-white-v3.png']]) {
  const source = `apps/website/static/${file}`;
  for (const width of widthSet) await derivative(source, `${website}/logo-${tone}-${width}.webp`, width, 'webp', { lossless: true, effort: 6 });
  for (const width of [180, 360, 720]) {
    const output = `${crm}/logo-${tone}-${width}.webp`;
    save(output, fs.readFileSync(`${website}/logo-${tone}-${width}.webp`));
    records.push({ ...records.find(item => item.output === `${website}/logo-${tone}-${width}.webp`), output });
  }
  // Keep the existing full-logo favicon design; only give it a small lossless file.
  await derivative(source, `${crm}/current-favicon-${tone}-64.png`, 64, 'png', { compressionLevel: 9, effort: 10 });
}
for (const [index, stem] of [[1, 'auto-nunes-martins-fachada'], [2, 'auto-nunes-martins-fachada-v2']]) {
  for (const width of [480, 640, 1024]) {
    const source = `apps/website/static/images/about/${stem}-1024.jpg`;
    await derivative(source, `${website}/facade-${index}-${width}.webp`, width, 'webp', { quality: 90, effort: 6, smartSubsample: true });
    await derivative(source, `${website}/facade-${index}-${width}.avif`, width, 'avif', { quality: 75, effort: 6, chromaSubsampling: '4:4:4' });
  }
}
// Small SVGs are already resolution independent; social previews keep their stable PNG URL.
save('docs/image-optimization/manifest.json', JSON.stringify({ note: 'Lanczos3, no crop/upscale. Logos: lossless WebP with original canvas/alpha. Photos: AVIF75 4:4:4, WebP90 fallback. Originals retained.', assets: records }, null, 2) + '\n');
for (const app of ['website', 'crm']) {
  const widths = app === 'website' ? widthSet : [180, 360, 720];
  let module = '// Generated by scripts/optimize-local-images.mjs. Keep width descriptors aligned with the files.\n';
  for (const tone of ['light', 'dark']) {
    for (const width of widths) module += `import ${tone}${width} from './assets/optimized/logo-${tone}-${width}.webp?url&no-inline';\n`;
    const title = tone === 'light' ? 'Light' : 'Dark';
    module += `export const logo${title} = ${tone}360;\nexport const logo${title}Srcset = \`${widths.map(width => '${' + tone + width + '} ' + width + 'w').join(', ')}\`;\n`;
  }
  if (app === 'website') {
    module += "export { default as catalogPlaceholder } from './assets/catalog-placeholder.svg?url&no-inline';\nexport { default as locationMap } from './assets/images/orbit-location-map.svg?url&no-inline';\n";
  } else {
    module += "export { default as faviconLight } from './assets/optimized/current-favicon-light-64.png?url&no-inline';\nexport { default as faviconDark } from './assets/optimized/current-favicon-dark-64.png?url&no-inline';\n";
  }
  save(`apps/${app}/src/lib/localAssets.ts`, module);
}
let photoModule = '// Generated from existing 1024 × 768 sources. Never choose a small variant from the clipped hero panel width.\n';
for (const index of [1, 2]) {
  for (const format of ['webp', 'avif']) for (const width of [480, 640, 1024]) photoModule += `import facade${index}${format}${width} from './assets/optimized/facade-${index}-${width}.${format}?url&no-inline';\n`;
  photoModule += `export const facade${index} = { src: facade${index}webp1024, avif: facade${index}avif1024, srcset: \`${[480, 640, 1024].map(width => '${facade' + index + 'webp' + width + '} ' + width + 'w').join(', ')}\`, avifSrcset: \`${[480, 640, 1024].map(width => '${facade' + index + 'avif' + width + '} ' + width + 'w').join(', ')}\` };\n`;
}
save('apps/website/src/lib/localPhotos.ts', photoModule);
console.log(`Created ${records.length} derivatives; originals retained. Details: docs/image-optimization/manifest.json`);
