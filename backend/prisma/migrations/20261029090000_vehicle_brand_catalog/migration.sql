CREATE FUNCTION anm_require_active_brand() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP='UPDATE' THEN IF NEW."brand" IS NOT DISTINCT FROM OLD."brand" THEN RETURN NEW; END IF; END IF;
 IF NOT EXISTS (SELECT 1 FROM "VehicleBrand" WHERE "name"=NEW."brand" AND "active") THEN RAISE EXCEPTION 'Selecione uma marca registada na lista.' USING ERRCODE='23514', CONSTRAINT='registered_vehicle_brand'; END IF;
 RETURN NEW; END $$;
CREATE TRIGGER "Vehicle_registered_brand" BEFORE INSERT OR UPDATE OF "brand" ON "Vehicle" FOR EACH ROW EXECUTE FUNCTION anm_require_active_brand();
CREATE TRIGGER "TradeIn_registered_brand" BEFORE INSERT OR UPDATE OF "brand" ON "TradeIn" FOR EACH ROW EXECUTE FUNCTION anm_require_active_brand();

